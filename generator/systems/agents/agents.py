# =============================================================== OpenAPI specs
ERR = {"type": "object", "properties": {"error": {"type": "string"}, "message": {"type": "string"}, "traceId": {"type": "string"}}}


def spec(title, version, server, paths, schemas, security):
    return {"openapi": "3.0.3", "info": {"title": title, "version": version}, "servers": [{"url": server}],
            "security": security["req"], "paths": paths,
            "components": {"securitySchemes": security["schemes"], "schemas": {"Error": ERR, **schemas}}}


def get(summary, params, resp_ref, tags):
    return {"get": {"summary": summary, "tags": tags, "parameters": params,
                    "responses": {"200": {"description": "OK", "content": {"application/json": {"schema": {"$ref": resp_ref}}}},
                                  "404": {"description": "Not found", "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Error"}}}},
                                  "429": {"description": "Rate limited"}}}}


def post(summary, req_ref, resp_ref, tags):
    return {"post": {"summary": summary, "tags": tags, "requestBody": {"required": True, "content": {"application/json": {"schema": {"$ref": req_ref}}}},
                     "responses": {"200": {"description": "OK", "content": {"application/json": {"schema": {"$ref": resp_ref}}}},
                                   "400": {"description": "Validation error", "content": {"application/json": {"schema": {"$ref": "#/components/schemas/Error"}}}},
                                   "409": {"description": "Business rule violation"}}}}


def q(name, required=False, desc="", typ="string", enum=None, inp="query"):
    p = {"name": name, "in": inp, "required": required, "description": desc, "schema": {"type": typ}}
    if enum:
        p["schema"]["enum"] = enum
    return p


