"""PLT-07: smoke test of the Fastweb API, one key per model (RFC §4.7, OQ-2/OQ-3).

Run from the repo root:  backend/.venv/bin/python scripts/smoke_fastweb.py [--wav file.wav]

Reads keys from `.secrets/fastweb_keys.json` via `tessera.core.config`, calls every configured
model and writes `docs/smoke-fastweb.md`. Prompts are hand-written here, not dataset text. The
report holds no secrets: only model ids, statuses, latencies and token counts.
"""

import argparse
import json
import math
import statistics
import time
from datetime import UTC, datetime
from pathlib import Path

from openai import APIStatusError, OpenAI
from pydantic import BaseModel, ValidationError

from tessera.core.config import REPO_ROOT, get_settings

EXTRACT_RUNS = 3
MARKER = "<!-- generated by scripts/smoke_fastweb.py below this line -->"
MAX_TOKENS = 2048

STOCK_TOOL = {
    "type": "function",
    "function": {
        "name": "get_stock",
        "description": "Returns units on hand for a SKU in a store",
        "parameters": {
            "type": "object",
            "properties": {"store_id": {"type": "string"}, "sku": {"type": "string"}},
            "required": ["store_id", "sku"],
        },
    },
}


class Observation(BaseModel):
    product_mention: str
    quote: str
    signal: str  # one of: stockout, high_demand, low_demand, other
    quantity: int | None = None


class Observations(BaseModel):
    observations: list[Observation]


def inline_refs(schema: dict) -> dict:
    """Replace `$ref` to `$defs` with the definition itself (Gemma ignores nested `$ref`)."""
    defs = schema.get("$defs", {})

    def walk(node):
        if isinstance(node, dict):
            if "$ref" in node:
                return walk(defs[node["$ref"].rsplit("/", 1)[-1]])
            return {k: walk(v) for k, v in node.items() if k != "$defs"}
        if isinstance(node, list):
            return [walk(v) for v in node]
        return node

    return walk(schema)


def extract_tool(parameters: dict) -> dict:
    return {
        "type": "function",
        "function": {
            "name": "submit_observations",
            "description": "Submit every demand signal in the email, quoting it verbatim.",
            "parameters": parameters,
        },
    }


EXTRACT_TOOL = extract_tool(inline_refs(Observations.model_json_schema()))
EXTRACT_TOOL_REF = extract_tool(Observations.model_json_schema())
EXTRACT_SYSTEM = (
    "You read store closing emails. Call submit_observations exactly once with every demand "
    "signal. `quote` must be copied verbatim from the email. `signal` is one of: stockout, "
    "high_demand, low_demand, other. Use null quantity when no number is stated."
)
EXTRACT_EMAIL = (
    "Oggi chiusura tranquilla. Il piumino lungo nero taglia 2 è finito a metà pomeriggio e "
    "almeno 4 clienti l'hanno chiesto. Le giacche leggere beige invece non si muovono."
)


def timed(fn):
    t = time.perf_counter()
    out = fn()
    return out, time.perf_counter() - t


def err(e: Exception) -> str:
    if isinstance(e, APIStatusError):
        return f"HTTP {e.status_code}"
    return type(e).__name__


def check_chat(client: OpenAI, model: str) -> dict:
    r, dt = timed(
        lambda: client.chat.completions.create(
            model=model,
            messages=[{"role": "user", "content": "Reply with just: ok"}],
            max_tokens=MAX_TOKENS,
        )
    )
    msg = r.choices[0].message
    return {
        "ok": "ok" in (msg.content or "").lower(),
        "latency_s": dt,
        "completion_tokens": r.usage.completion_tokens if r.usage else None,
        "reasoning": bool(
            getattr(msg, "reasoning", None) or (msg.model_extra or {}).get("reasoning")
        ),
    }


def check_tool_round_trip(client: OpenAI, model: str) -> dict:
    messages = [{"role": "user", "content": "Quante unità di 1A00010-999 ha il negozio MIL01?"}]
    r, dt1 = timed(
        lambda: client.chat.completions.create(
            model=model,
            messages=messages,
            tools=[STOCK_TOOL],
            tool_choice="auto",
            max_tokens=MAX_TOKENS,
        )
    )
    msg = r.choices[0].message
    calls = msg.tool_calls or []
    if not calls:
        return {"tool_call": False, "finish_reason": r.choices[0].finish_reason, "latency_s": dt1}
    call = calls[0]
    args = json.loads(call.function.arguments)
    messages += [
        {"role": "assistant", "tool_calls": [call.model_dump(include={"id", "type", "function"})]},
        {"role": "tool", "tool_call_id": call.id, "content": json.dumps({"units": 7})},
    ]
    r2, dt2 = timed(
        lambda: client.chat.completions.create(
            model=model, messages=messages, tools=[STOCK_TOOL], max_tokens=MAX_TOKENS
        )
    )
    answer = r2.choices[0].message.content or ""
    return {
        "tool_call": True,
        "finish_reason": r.choices[0].finish_reason,
        "args_ok": args == {"store_id": "MIL01", "sku": "1A00010-999"},
        "answer_uses_result": "7" in answer,
        "latency_s": dt1 + dt2,
    }


def extract_once(client: OpenAI, model: str, tool_choice, tool=EXTRACT_TOOL) -> tuple[str, float]:
    """Return outcome: valid / invalid / no_tool / HTTP error, plus latency."""
    try:
        r, dt = timed(
            lambda: client.chat.completions.create(
                model=model,
                messages=[
                    {"role": "system", "content": EXTRACT_SYSTEM},
                    {"role": "user", "content": EXTRACT_EMAIL},
                ],
                tools=[tool],
                tool_choice=tool_choice,
                max_tokens=MAX_TOKENS,
            )
        )
    except Exception as e:  # report, don't abort the smoke run
        return err(e), 0.0
    calls = r.choices[0].message.tool_calls or []
    if not calls:
        return "no_tool", dt
    try:
        obs = Observations.model_validate_json(calls[0].function.arguments).observations
    except ValidationError:
        return "invalid", dt
    quotes_ok = obs and all(o.quote in EXTRACT_EMAIL for o in obs)
    return ("valid" if quotes_ok else "valid_bad_quote"), dt


def check_extract(client: OpenAI, model: str) -> dict:
    runs = [extract_once(client, model, "auto") for _ in range(EXTRACT_RUNS)]
    forced_fn, _ = extract_once(
        client, model, {"type": "function", "function": {"name": "submit_observations"}}
    )
    required, _ = extract_once(client, model, "required")
    with_ref, _ = extract_once(client, model, "auto", EXTRACT_TOOL_REF)
    return {
        "auto": [o for o, _ in runs],
        "latency_s": statistics.median(dt for _, dt in runs),
        "forced_function": forced_fn,
        "required": required,
        "with_ref": with_ref,
    }


def cosine(a: list[float], b: list[float]) -> float:
    dot = sum(x * y for x, y in zip(a, b, strict=True))
    return dot / (math.sqrt(sum(x * x for x in a)) * math.sqrt(sum(y * y for y in b)))


def check_embed(client: OpenAI, model: str) -> dict:
    texts = [
        "Il piumino lungo nero è esaurito.",
        "The long black down jacket is sold out.",
        "Il negozio chiude alle 20 di sabato.",
    ]
    out = {}
    for dims in (512, 2048):
        r, dt = timed(
            lambda d=dims: client.embeddings.create(model=model, input=texts, dimensions=d)
        )
        v = [d.embedding for d in r.data]
        out[dims] = {
            "len": len(v[0]),
            "latency_s": dt,
            "sim_paraphrase": cosine(v[0], v[1]),
            "sim_unrelated": cosine(v[0], v[2]),
        }
    return out


def check_asr(client: OpenAI, model: str, wav: Path) -> dict:
    with wav.open("rb") as f:
        r, dt = timed(
            lambda: client.audio.transcriptions.create(
                model=model, file=f, response_format="verbose_json"
            )
        )
    segments = getattr(r, "segments", None) or []
    return {"latency_s": dt, "chars": len(r.text), "segments": len(segments)}


def run(wav: Path | None) -> dict:
    s = get_settings()
    keys = s.fastweb_keys()
    results: dict = {"chat": {}, "embed": {}, "asr": None}
    for model, key in keys.items():
        client = OpenAI(
            base_url=s.fastweb_base_url, api_key=key.get_secret_value(), timeout=120, max_retries=1
        )
        print(f"… {model}", flush=True)
        if model == s.embed_model:
            results["embed"][model] = check_embed(client, model)
        elif model == s.asr_model:
            results["asr"] = (
                check_asr(client, model, wav) if wav else {"skipped": "key present, no --wav given"}
            )
        else:
            res = {}
            for name, fn in [
                ("chat", check_chat),
                ("tools", check_tool_round_trip),
                ("extract", check_extract),
            ]:
                try:
                    res[name] = fn(client, model)
                except Exception as e:  # report, don't abort the smoke run
                    res[name] = {"error": err(e)}
            results["chat"][model] = res
    if results["asr"] is None:
        results["asr"] = {"skipped": f"no key for {s.asr_model}"}
    return results


def yn(v) -> str:
    return "✅" if v else "❌"


def report(results: dict, chat_default: str, base_url: str) -> str:
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "## Measurements",
        "",
        f"Generated by `scripts/smoke_fastweb.py` on {now}. Base URL `{base_url}`. "
        "One key per model in `.secrets/fastweb_keys.json` (gitignored). No secrets here.",
        "",
        "### Chat models",
        "",
        "Plain chat with `max_tokens` "
        f"{MAX_TOKENS}; tool round trip = `get_stock` with `tool_choice=auto`, result sent back; "
        f"extract = single tool `submit_observations` on a hand-written Italian email, "
        f"{EXTRACT_RUNS} runs with `auto`, then one forced by name, one `required`, all with "
        "`$defs` inlined; last column: one `auto` run with the raw Pydantic schema (`$ref`). "
        "Latency in seconds (extract: median).",
        "",
        "| Model | Chat | Reasoning | Chat s | Tool call | Args | Uses result | Tool s "
        "| Extract auto | Extract s | Forced by name | `required` | `$ref` schema |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for model, r in results["chat"].items():
        c, t, e = r["chat"], r["tools"], r["extract"]
        row = [f"`{model}`"]
        row += (
            [yn(c["ok"]), yn(c["reasoning"]), f"{c['latency_s']:.1f}"]
            if "error" not in c
            else [c["error"], "", ""]
        )
        if "error" in t:
            row += [t["error"], "", "", ""]
        elif not t["tool_call"]:
            row += [f"❌ ({t['finish_reason']})", "", "", f"{t['latency_s']:.1f}"]
        else:
            row += [
                yn(True),
                yn(t["args_ok"]),
                yn(t["answer_uses_result"]),
                f"{t['latency_s']:.1f}",
            ]
        if "error" in e:
            row += [e["error"], "", "", "", ""]
        else:
            valid = sum(o == "valid" for o in e["auto"])
            row += [
                f"{valid}/{len(e['auto'])} ({', '.join(e['auto'])})",
                f"{e['latency_s']:.1f}",
                e["forced_function"],
                e["required"],
                e["with_ref"],
            ]
        lines.append("| " + " | ".join(row) + " |")
    lines += ["", "### Embeddings", ""]
    for model, r in results["embed"].items():
        lines += [
            "| Model | dimensions | Vector length | s | cos(it, en paraphrase) | cos(unrelated) |",
            "|---|---|---|---|---|---|",
        ]
        for dims, d in r.items():
            lines.append(
                f"| `{model}` | {dims} | {d['len']} | {d['latency_s']:.2f} "
                f"| {d['sim_paraphrase']:.3f} | {d['sim_unrelated']:.3f} |"
            )
    lines += ["", "### Speech-to-text", ""]
    asr = results["asr"]
    if "skipped" in asr:
        lines.append(f"Not tested: {asr['skipped']}.")
    else:
        lines.append(
            f"{asr['latency_s']:.1f} s, {asr['chars']} chars, {asr['segments']} segments "
            "(`verbose_json`)."
        )
    lines += ["", f"Configured chat default: `{chat_default}`.", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--wav", type=Path, help="audio file for the ASR check")
    ap.add_argument("--out", type=Path, default=REPO_ROOT / "docs" / "smoke-fastweb.md")
    args = ap.parse_args()
    s = get_settings()
    results = run(args.wav)
    # Hand-written findings above the marker survive a re-run; the measurements are replaced.
    head = ""
    if args.out.is_file() and MARKER in args.out.read_text():
        head = args.out.read_text().split(MARKER)[0]
    args.out.write_text(head + MARKER + "\n\n" + report(results, s.chat_model, s.fastweb_base_url))
    print(f"wrote {args.out.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
